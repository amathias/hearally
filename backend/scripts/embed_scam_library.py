"""Embed the curated scam library and write src/hearally/scam_embeddings.json.

Run after adding or editing a card in scam_cards.json. A test fails while any
card's vector is missing or stale, so a forgotten run is caught in CI.

    python backend/scripts/embed_scam_library.py

Reads the Nebius key from Secrets Manager through the AWS CLI, into memory
only; it is never printed or written.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from hearally.scam_library import (  # noqa: E402
    _VECTORS_FILE,
    EMBEDDING_MODEL,
    EmbeddingClient,
    encode_vector,
    load_curated,
)


def nebius_key() -> str:
    return subprocess.run(
        [
            "aws",
            "secretsmanager",
            "get-secret-value",
            "--secret-id",
            "hearally-prod/nebius-api-key",
            "--region",
            "us-east-1",
            "--query",
            "SecretString",
            "--output",
            "text",
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def main() -> None:
    cards = load_curated()
    key = nebius_key()
    vectors = EmbeddingClient(lambda: key).embed([card.text() for card in cards])
    out = {
        "model": EMBEDDING_MODEL,
        "about": "Generated by backend/scripts/embed_scam_library.py. Do not edit.",
        "cards": {
            card.id: {"fingerprint": card.fingerprint(), "vector": encode_vector(vector)}
            for card, vector in zip(cards, vectors, strict=True)
        },
    }
    _VECTORS_FILE.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print(f"embedded {len(cards)} cards, {len(vectors[0])} dimensions -> {_VECTORS_FILE.name}")


if __name__ == "__main__":
    main()
